// Helper voor meldingen: pak veld (titel/bericht) in huidige taal, met
// fallback-keten: huidige taal → EN → NL (= origineel). Vertaalde velden
// (titel_en, titel_de, titel_fr) worden door backend gevuld via Claude AI
// bij save. NL-veld (titel, bericht) is altijd verplicht; vertalingen
// optioneel. Voor talen waar de vertaling ontbreekt → val terug op EN
// (de meest universele) en uiteindelijk op NL.
function _meldingTekst(m, veld) {
    const lang = getCurLang();
    const sufLang = veld + '_' + lang;
    const sufEn   = veld + '_en';
    if (lang !== 'nl' && m[sufLang]) return m[sufLang];
    if (lang !== 'nl' && m[sufEn])   return m[sufEn];
    return m[veld] || '';
}

function _rerenderActiveTab() {
    // Comps-dropdown opnieuw vullen (textContent gebruikt vertaalde labels)
    if (typeof filterComps === 'function' && alleComps?.length) filterComps();
    // Multi-rijder view opnieuw renderen
    if (typeof renderKinderen === 'function' && _kinderen?.length) {
        _bewaarKindUistate?.();
        renderKinderen();
    }
    // Connection banner updaten
    if (typeof _connUpdateBanner === 'function') _connUpdateBanner();
    // Stempel-tekst opnieuw zetten (title-attribute)
    document.querySelectorAll('.auto-stempel').forEach(el => {
        el.title = t('auto_stempel_title');
    });
    // Meldingen-badge: alleen een getal, geen vertaling nodig.
    // Maar openstaande melding-overlays bevatten al-gerenderde titel/bericht
    // in de oude taal — die moeten we opnieuw bouwen, anders zie je na
    // NL→EN nog steeds de Nederlandse tekst staan (vooral merkbaar bij
    // globale meldingen die direct bij landing openstaan).
    const popup = document.querySelector('[data-meld-overlay="popup"]');
    if (popup && _huidigeMelding) {
        const m = _huidigeMelding;
        popup.remove();
        _meldingActief = false;
        _huidigeMelding = null;
        toonMelding(m, selComp?.value || '');
    }
    const overz = document.querySelector('[data-meld-overlay="overzicht"]');
    if (overz) {
        overz.remove();
        toonMeldingenOverzicht();
    }
    // Fase 5a: dynamische content in hub-view + org-detail-view wordt via
    // t() in template-literals geschreven; die blijft in de oude taal hangen
    // bij een taalwissel. Herbouwen zodat alle labels/periode-headers/tag-
    // tekst in de nieuwe taal verschijnen. Caches blijven staan — geen
    // refetch, alleen re-render.
    const hub = document.getElementById('hub-view');
    if (hub && !hub.hidden) {
        const actieveTab = document.querySelector('.wmodal-tab.actief')?.dataset.tab;
        if (actieveTab === 'wedstrijden' && typeof _renderWedstrijdLijst === 'function' && _wmodalComps) {
            _renderWedstrijdLijst();
        } else if (actieveTab === 'organisaties' && typeof _renderOrganisatieLijst === 'function' && _wmodalOrgCache) {
            _renderOrganisatieLijst(_wmodalOrgCache);
        }
    }
    // Wedstrijd-info-view heeft voorrang: als die open staat, is _wmodalAktieveOrg
    // misschien ook gezet, maar we willen de info-view herbouwen (niet terug naar org).
    if (typeof _toonWedstrijdInfoView === 'function' && _aktieveWedstrijdInfo) {
        const prevWiTab = document.querySelector('.wi-view .org-view-tab.actief')?.dataset.tab;
        _toonWedstrijdInfoView(_aktieveWedstrijdInfo);
        if (prevWiTab && prevWiTab !== 'infobulletin' && typeof switchWiTab === 'function') {
            switchWiTab(prevWiTab);
        }
    } else if (typeof _toonOrganisatieView === 'function' && _wmodalAktieveOrg) {
        // Onthoud actieve org-tab vóór rebuild — _toonOrganisatieView
        // start default op 'agenda', wat na een taalwissel bij een gebruiker
        // die net Algemeen/Nieuws aan het bekijken was een tab-sprong geeft.
        const prevTab = document.querySelector('.org-view-tab.actief')?.dataset.tab;
        _toonOrganisatieView(_wmodalAktieveOrg);
        if (prevTab && prevTab !== 'agenda' && typeof switchOrgTab === 'function') {
            switchOrgTab(prevTab);
        }
    }
    // De zojuist herbouwde dynamische content bevat verse data-i18n-elementen
    // met de NL-fallback-tekst in de span. applyI18n liep aan het begin van
    // deze callback (door setLang), dus moet nu opnieuw over de nieuwe DOM
    // om die fallbacks te vervangen door de actuele taal.
    if (typeof applyI18n === 'function') applyI18n();
}

